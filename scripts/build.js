import {build} from 'esbuild';
import {cpSync,mkdirSync,writeFileSync,existsSync,rmSync} from 'node:fs';
await build({entryPoints:['scripts/qr-entry.cjs'],bundle:true,minify:true,platform:'browser',outfile:'public/qr.js'});
const media={};
for(const name of ['products','laundry','living','kitchen']){
 const extension=['jpg','jpeg','png','webp'].find(ext=>existsSync(`public/assets/${name}.${ext}`));
 media[name]=extension?`./assets/${name}.${extension}`:null;
}
writeFileSync('public/media-manifest.js','// Generated by npm run build from available original image files.\nexport const media='+JSON.stringify(media,null,2)+';\n');
// Recreate generated output so removed images cannot remain in releases.
rmSync('dist',{recursive:true,force:true});mkdirSync('dist',{recursive:true});
for(const file of ['index.html','app.js','style.css','demo.js','catalog.js','qr.js','media.js','media-manifest.js'])cpSync('public/'+file,'dist/'+file);
if(Object.values(media).some(Boolean))mkdirSync('dist/assets',{recursive:true});
for(const path of Object.values(media).filter(Boolean))cpSync('public/'+path.slice(2),'dist/'+path.slice(2));
writeFileSync('dist/.nojekyll','');
console.log('Static H5 ready in dist/. Original uploaded images available: '+Object.values(media).filter(Boolean).length+'/4.');
